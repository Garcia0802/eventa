export const getUserInterests = (user = {}) => {
  return [user.category_1, user.category_2, user.category_3].filter(Boolean);
};

export const getInterestCategory = (interest) => {
  if (!interest) {
    return null;
  }

  return INTEREST_CATEGORY_MAP[interest] || null;
};

export const normalizeInterestKey = (value) => {
  if (!value) {
    return '';
  }

  return String(value)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
};
